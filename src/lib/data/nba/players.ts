const _ = null;
const UPDATED = "2026-11-06";
type N = number | null;

export function slug(s: string): string {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

export function decadeOf(startYear: number): Decade {
  return `${Math.floor(startYear / 10) * 10}s` as Decade;
}

function r(name: string, fr: string, y: number, pos: string, gp: N, ppg: number, rpg: number, apg: number,
  spg: N, bpg: N, fg: N, tp: N, tpa: N, ft: N, d = 0): NbaPlayerSeason {
  const playerId = slug(name);
  const pre73 = y < 1973, pre79 = y < 1979;
  return {
    id: `${playerId}-${fr.toLowerCase()}-${y}`,
    playerId, name, franchiseId: fr, teamName: teamNameFor(fr, y), startYear: y,
    season: `${y}-${String((y + 1) % 100).padStart(2, "0")}`,
    decade: decadeOf(y),
    positions: pos.split("/") as NbaPos[],
    gp, ppg, rpg, apg,
    spg: pre73 ? null : spg, bpg: pre73 ? null : bpg,
    fgPct: fg, tpPct: pre79 ? null : tp, tpa: pre79 ? null : tpa, ftPct: ft,
    defRep: d,
    source: "Public box-score records (manual curation)",
    verification: "manual-curation",
    updatedAt: UPDATED,
  };
}

