import type { FbDecade, FbPlayerSeason, FbPos, FbStyle } from "@/types/football";
import { estimateAttributes } from "@/lib/ratings/football";

const UPDATED = "2026-11-06";
export function fbSlug(s: string): string {
  return s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}
function p(name: string, nation: string, clubId: string, y: number, pos: string, ovr: number, style: FbStyle, goals: number | null = null): FbPlayerSeason {
  const playerId = fbSlug(name);
  const id = `${playerId}-${clubId.toLowerCase()}-${y}`;
  const positions = pos.split("/") as FbPos[];
  const { attrs, gk } = estimateAttributes({ id, ovr, style, positions });
  return {
    id, playerId, name, nation, clubId, startYear: y, season: `${y}/${String((y + 1) % 100).padStart(2, "0")}`,
    decade: `${Math.floor(y / 10) * 10}s` as FbDecade, positions, ovr, style, attrs, gk, leagueGoals: goals,
    attrsEstimated: true, source: "Public club/season records (manual curation)", verification: "manual-curation", updatedAt: UPDATED,
  };
}

